#!/usr/bin/env node
/**
 * Scan public/maps/stations/*.png and write src/data/stationMapAvailability.ts
 * so the app can hide area-map UI when the asset is missing (no broken <img>).
 *
 *   node scripts/write-station-map-availability.mjs
 */
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const mapDir = join(root, "public/maps/stations");
const outPath = join(root, "src/data/stationMapAvailability.ts");

export function writeStationMapAvailability(rootDir = root) {
  const dir = join(rootDir, "public/maps/stations");
  const out = join(rootDir, "src/data/stationMapAvailability.ts");
  mkdirSync(dirname(out), { recursive: true });

  const slugs = readdirSync(dir)
    .filter((file) => file.endsWith(".png"))
    .map((file) => file.slice(0, -4))
    .sort((a, b) => a.localeCompare(b));

  const content = `// Auto-generated by scripts/write-station-map-availability.mjs — do not edit.
/** Station slugs that have a PNG under public/maps/stations/. */
export const stationMapAvailability: ReadonlySet<string> = new Set([
${slugs.map((slug) => `  ${JSON.stringify(slug)},`).join("\n")}
]);
`;
  writeFileSync(out, content);
  return { count: slugs.length, out };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const { count, out } = writeStationMapAvailability();
  console.log(`Wrote ${count} map slug(s) → ${out}`);
}
