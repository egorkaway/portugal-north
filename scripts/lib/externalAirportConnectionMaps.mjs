export const EXTERNAL_MAPS_REL = "public/maps/airports/external";
export const EXTERNAL_STORE_REL = "data/external-airport-connection-maps.json";
const PAGE_IATAS_REL = "src/data/externalAirportPageIatas.ts";

export function externalMapsDir(rootDir) {
  return join(rootDir, EXTERNAL_MAPS_REL);
}

export function externalStorePath(rootDir) {
  return join(rootDir, EXTERNAL_STORE_REL);
}

export function loadExternalAirportMapsStore(rootDir) {
  try {
    const raw = JSON.parse(readFileSync(externalStorePath(rootDir), "utf8"));
    const airports = Array.isArray(raw?.airports) ? raw.airports : [];
    let dirty = false;
    const migrated = airports.map((row) => {
      const next = migrateLegacyIberianRow(rootDir, row);
      if (next !== row) dirty = true;
      return next;
    });
    const store = {
      updatedAt: typeof raw?.updatedAt === "string" ? raw.updatedAt : null,
      airports: migrated,
    };
    if (dirty) saveExternalAirportMapsStore(rootDir, store);
    return store;
  } catch {
    return { updatedAt: null, airports: [] };
  }
}

export function saveExternalAirportMapsStore(rootDir, store) {
  const outPath = externalStorePath(rootDir);
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, `${JSON.stringify(store, null, 2)}\n`);
  writeExternalAirportPageIatas(rootDir, store);
  return outPath;
}

export function writeExternalAirportPageIatas(rootDir, store) {
  const iatas = (store?.airports ?? [])
    .map((row) => normalizeExternalAirportRow(row))
    .filter((row) => hasBothExternalMaps(row))
    .map((row) => String(row.iata ?? "").trim().toUpperCase())
    .filter(Boolean)
    .sort();
  const unique = [...new Set(iatas)];
  const body = `/** Auto-generated by scripts/lib/externalAirportConnectionMaps.mjs — do not edit. */\nexport const EXTERNAL_AIRPORT_PAGE_IATAS: readonly string[] = ${JSON.stringify(unique, null, 2)};\n`;
  const outPath = join(rootDir, PAGE_IATAS_REL);
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, body);
  return outPath;
}

function migrateLegacyIberianRow(rootDir, row) {
  const normalized = normalizeExternalAirportRow(row);
  const slug = normalized.slug;
  if (
    slug &&
    hasIberianMap(normalized) &&
    !hasAllFlightsMap(normalized)
  ) {
    const mapsDir = externalMapsDir(rootDir);
    const dest = join(mapsDir, externalMapFilename(slug, "iberian"));
    const legacy = join(mapsDir, externalMapFilename(slug, "all"));
    if (existsSync(legacy) && !existsSync(dest)) {
      renameSync(legacy, dest);
    }
  }
  return normalized;
}

function hubIataSet(rootDir) {
  return new Set(
    loadAirportCatalog(rootDir)
      .map((airport) => airport.iata?.toUpperCase())
      .filter(Boolean),
  );
}

export function chooseExternalAirportForRun(
  rootDir,
  manifest,
  coordinates,
  store,
  options = {},
) {
  const ranked = rankExternalAirportsFromManifest(
    manifest,
    hubIataSet(rootDir),
    coordinates,
  );
  const sampled = coverageFromExternalMapRows(store?.airports ?? []);
  const pick = pickExternalAirportForRun(ranked, sampled, options);
  if (!pick) return { ranked, pick: null, coords: null, stationName: null, slug: null };
  const coords = coordinates[pick.iata];
  const stationName = externalAirportDisplayName(pick.iata, coords);
  return {
    ranked,
    pick,
    coords,
    stationName,
    slug: stationToSlug(stationName),
  };
}

function hubNetwork(manifest) {
  const byIata = new Map();
  for (const entry of Object.values(manifest?.fallbackAirports ?? {})) {
    const iata = entry.iata?.trim().toUpperCase();
    if (iata) byIata.set(iata, entry);
  }
  for (const entry of Object.values(manifest?.airports ?? {})) {
    const iata = entry.iata?.trim().toUpperCase();
    if (iata) byIata.set(iata, entry);
  }
  return [...byIata.values()];
}

function buildIberianInboundEntry({
  pick,
  coords,
  stationName,
  slug,
  manifest,
  coordinates,
}) {
  const dest = pick.iata;
  const connections = [];
  for (const hub of hubNetwork(manifest)) {
    const originIata = hub.iata?.trim().toUpperCase();
    if (!originIata || originIata === dest) continue;
    const inbound = (hub.connections ?? []).find(
      (connection) => connection.iata?.trim().toUpperCase() === dest,
    );
    if (!inbound) continue;
    const origin = hub.origin;
    if (!origin || !Number.isFinite(origin.lat) || !Number.isFinite(origin.lng)) continue;
    const hubCoords = coordinates[originIata];
    const flightCount = inbound.flightCount || 0;
    connections.push({
      iata: originIata,
      name: hub.stationName || hubCoords?.name || originIata,
      country: formatCountryName(hubCoords?.country || ""),
      lat: origin.lat,
      lng: origin.lng,
      flightCount,
      flights: inbound.flights ?? [],
      lineColor: getFlightLineColor(flightCount),
      lineWeight: getFlightLineWeight(flightCount),
    });
  }
  connections.sort(
    (a, b) => b.flightCount - a.flightCount || a.name.localeCompare(b.name),
  );
  if (!connections.length) return null;
  return {
    stationName,
    slug,
    iata: dest,
    origin: { lat: coords.lat, lng: coords.lng },
    sampledFlights: pick.iberianFlightCount,
    connections,
    topDestinations: connections.slice(0, 10),
    mapImage: externalMapPublicPath(slug, "iberian"),
  };
}

function existingMapRow(store, iata) {
  const code = String(iata ?? "").toUpperCase();
  const row =
    (store?.airports ?? []).find((entry) => String(entry.iata ?? "").toUpperCase() === code) ??
    null;
  return row ? normalizeExternalAirportRow(row) : null;
}

function mergeAirportRow(store, patch) {
  const airports = [...(store.airports ?? [])];
  const index = airports.findIndex((entry) => entry.iata === patch.iata);
  const previous = index >= 0 ? normalizeExternalAirportRow(airports[index]) : {};
  const merged = { ...previous, ...patch };
  if (index >= 0) airports[index] = merged;
  else airports.push(merged);
  return {
    updatedAt: patch.iberianSampledAt || patch.sampledAt || previous.updatedAt || null,
    airports,
  };
}

async function persistExternalAirportMap({
  rootDir,
  store,
  entry,
  pick,
  coords,
  stationName,
  slug,
  provider,
  periodId,
  siteUrl,
  basemapMode,
  renderAirportConnectionsMap,
  kind,
}) {
  const publicPath = externalMapPublicPath(slug, kind);
  entry.mapImage = publicPath;
  const png = await renderAirportConnectionsMap(entry, {
    siteUrl,
    basemapMode,
    showStationPageUrl: true,
    connectionScope: kind,
  });
  const mapsDir = externalMapsDir(rootDir);
  mkdirSync(mapsDir, { recursive: true });
  writeFileSync(join(mapsDir, externalMapFilename(slug, kind)), png.buffer);

  const sampledAt = new Date().toISOString();
  const patch = {
    iata: pick.iata,
    stationName,
    slug,
    country: coords.country ?? "",
    iberianFlightCount: pick.iberianFlightCount,
  };
  if (kind === "iberian") {
    Object.assign(patch, {
      iberianMapImage: publicPath,
      iberianDestinationCount: entry.connections.length,
      iberianSampledFlights: entry.sampledFlights,
      iberianSampledAt: sampledAt,
      iberianPeriodId: periodId,
      iberianBasemapId: png.basemapId,
    });
  } else {
    Object.assign(patch, {
      mapImage: publicPath,
      destinationCount: entry.connections.length,
      sampledFlights: entry.sampledFlights,
      sampledAt,
      periodId,
      provider,
      basemapId: png.basemapId,
    });
  }

  const nextStore = mergeAirportRow(store, patch);
  saveExternalAirportMapsStore(rootDir, nextStore);
  const label = `${stationName} (${pick.iata})`;
  const action =
    kind === "iberian" ? "Iberian flights map" : "all-flights map";
  console.log(
    `External spotlight ${label}: ${entry.connections.length} destinations` +
      ` (${pick.iberianFlightCount} Iberian flights in) ${action} via ${provider} (${png.basemapId})`,
  );
  return { store: nextStore, skipped: false, skipReason: null, pick, entry };
}

function iberianInboundForChosen(chosen, manifest, coordinates) {
  return buildIberianInboundEntry({
    pick: chosen.pick,
    coords: chosen.coords,
    stationName: chosen.stationName,
    slug: chosen.slug,
    manifest,
    coordinates,
  });
}

/**
 * One external map per collect step. Iberian and all-flights maps are kept separately.
 * APIs down: Iberian map for the next airport that is missing one.
 * APIs up: all-flights map (without replacing the Iberian image).
 */
export async function sampleExternalAirportConnectionMap(options) {
  const {
    rootDir,
    manifest,
    coordinates,
    fetchDepartures,
    resolveMissingCoordinates,
    buildAirportConnections,
    renderAirportConnectionsMap,
    siteUrl,
    basemapMode = "osm",
    periodId = null,
    dryRun = false,
    skip = false,
    skipReason = null,
    flightApisAvailable = true,
  } = options;

  const store = loadExternalAirportMapsStore(rootDir);
  if (skip) {
    return { store, skipped: true, skipReason, pick: null };
  }

  const persist = (chosen, entry, provider, kind) =>
    persistExternalAirportMap({
      rootDir,
      store,
      entry,
      pick: chosen.pick,
      coords: chosen.coords,
      stationName: chosen.stationName,
      slug: chosen.slug,
      provider,
      periodId,
      siteUrl,
      basemapMode,
      renderAirportConnectionsMap,
      kind,
    });

  const chosen = chooseExternalAirportForRun(rootDir, manifest, coordinates, store, {
    flightApisAvailable,
  });
  if (!chosen.pick || !chosen.coords) {
    return {
      store,
      skipped: true,
      skipReason: flightApisAvailable ? "no-external-destination" : "no-unmapped-external",
      pick: null,
    };
  }

  const { pick, coords, stationName } = chosen;
  const label = `${stationName} (${pick.iata})`;
  const existing = existingMapRow(store, pick.iata);

  if (dryRun) {
    const intent = !flightApisAvailable
      ? `Iberian flights map (${pick.iberianFlightCount} Iberian flights)`
      : existing && hasAllFlightsMap(existing)
        ? `refresh all-flights map`
        : `all-flights map (${pick.iberianFlightCount} Iberian flights in)`;
    console.log(`[dry-run] External spotlight: ${label} — ${intent}`);
    return { store, skipped: true, skipReason: "dry-run", pick };
  }

  if (!flightApisAvailable) {
    const inbound = iberianInboundForChosen(chosen, manifest, coordinates);
    if (!inbound) {
      console.warn(`External spotlight ${label}: no mappable Iberian destinations`);
      return { store, skipped: true, skipReason: "no-connections", pick };
    }
    return persist(chosen, inbound, IBERIAN_INBOUND_PROVIDER, "iberian");
  }

  const synthetic = {
    stationName,
    slug: chosen.slug,
    iata: pick.iata,
    name: coords.name || pick.iata,
    lat: coords.lat,
    lng: coords.lng,
    countryCode: "pt",
  };

  try {
    const sample = await fetchDepartures(pick.iata, 100);
    const destIatas = [
      ...new Set(
        sample.flights
          .map((flight) => flight.arrival?.iata?.trim().toUpperCase())
          .filter((iata) => iata && iata !== pick.iata),
      ),
    ];
    await resolveMissingCoordinates(destIatas.filter((iata) => !coordinates[iata]));
    const entry = buildAirportConnections(synthetic, sample.flights, coordinates);
    if (!entry?.connections?.length) {
      throw new Error("outbound sample returned no mappable destinations");
    }
    return persist(chosen, entry, sample.provider, "all");
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    if (!existing || !hasIberianMap(existing)) {
      console.warn(
        `Flight APIs are out of monthly quota, so I'll build the Iberian flights map from connections we already have: ${label}. (${message})`,
      );
      const inbound = iberianInboundForChosen(chosen, manifest, coordinates);
      if (!inbound) {
        console.warn(`External spotlight ${label}: no mappable destinations`);
        return { store, skipped: true, skipReason: "no-connections", pick };
      }
      return persist(chosen, inbound, IBERIAN_INBOUND_PROVIDER, "iberian");
    }

    console.warn(
      `External spotlight ${label}: all-flights sample failed (${message}); keeping existing maps.`,
    );

    const fallback = chooseExternalAirportForRun(rootDir, manifest, coordinates, store, {
      flightApisAvailable: false,
    });
    if (!fallback.pick || !fallback.coords || fallback.pick.iata === pick.iata) {
      return {
        store,
        skipped: true,
        skipReason: "keep-existing",
        pick,
      };
    }

    const fallbackLabel = `${fallback.stationName} (${fallback.pick.iata})`;
    const inbound = iberianInboundForChosen(fallback, manifest, coordinates);
    if (!inbound) {
      console.warn(`External spotlight ${fallbackLabel}: no mappable Iberian destinations`);
      return {
        store,
        skipped: true,
        skipReason: "keep-existing",
        pick,
      };
    }
    console.warn(
      `Drawing the Iberian flights map for ${fallbackLabel} while APIs are down.`,
    );
    return persist(fallback, inbound, IBERIAN_INBOUND_PROVIDER, "iberian");
  }
}

